#!/usr/bin/env python3
"""Generate the app's offline full Jio channel catalogue.

The generated TypeScript is committed and bundled with the app. Runtime channel
search never calls Jio or any other cloud service.
"""

from __future__ import annotations

import json
import re
import shutil
from concurrent.futures import ThreadPoolExecutor, as_completed
from hashlib import sha1
from pathlib import Path
from urllib.parse import urlencode, urlparse
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "mobile" / "src" / "jioChannels.generated.ts"
LOGO_DIRECTORY = ROOT / "mobile" / "public" / "channel-logos" / "all"
GUIDE_URL = "https://www.jio.com/jcms-api/master-lookups?" + urlencode(
    {"filters[label][$eq]": "AIRFIBER_CHANNELS"}
)


def content_id(image: object) -> str | None:
    match = re.search(r"/(\d+)_", str(image or ""))
    return match.group(1) if match else None


def logo_filename(channel: dict[str, object], identifier: str | None) -> str:
    image = str(channel.get("image") or "")
    suffix = Path(urlparse(image).path).suffix.lower()
    if suffix not in {".jpg", ".jpeg", ".png", ".webp"}:
        suffix = ".jpg"
    name = re.sub(r"[^a-z0-9]+", "-", str(channel["name"]).casefold()).strip("-")[:36]
    stable_id = identifier or sha1(image.encode()).hexdigest()[:12]
    return f"{int(channel['channelNumber'])}-{stable_id}-{name}{suffix}"


def download_logo(channel: dict[str, object], filename: str) -> tuple[str, str | None]:
    image = str(channel.get("image") or "")
    if not image:
        return filename, "missing image URL"
    try:
        request = Request(image, headers={"Accept": "image/*", "User-Agent": "Family-TV-Remote/1.0"})
        with urlopen(request, timeout=20) as response:
            data = response.read()
        if len(data) < 100:
            raise ValueError("empty image")
        (LOGO_DIRECTORY / filename).write_bytes(data)
        return filename, None
    except Exception as error:  # A failed logo keeps the initials fallback.
        return filename, str(error)


def load_guide() -> tuple[str, list[dict[str, object]]]:
    request = Request(
        GUIDE_URL,
        headers={"Accept": "application/json", "User-Agent": "Family-TV-Remote/1.0"},
    )
    with urlopen(request, timeout=30) as response:
        payload = json.load(response)
    attributes = payload["data"][0]["attributes"]
    return attributes["updatedAt"], attributes["value"]["channelsData"]["data"]


def main() -> None:
    updated_at, source = load_guide()
    LOGO_DIRECTORY.parent.mkdir(parents=True, exist_ok=True)
    shutil.rmtree(LOGO_DIRECTORY, ignore_errors=True)
    LOGO_DIRECTORY.mkdir(parents=True)

    logo_jobs: list[tuple[dict[str, object], str]] = []
    channels = []
    for channel in source:
        number = int(channel["channelNumber"])
        name = str(channel["name"]).strip()
        identifier = content_id(channel.get("image"))
        filename = logo_filename(channel, identifier)
        logo_jobs.append((channel, filename))
        genres = [str(value).strip() for value in channel.get("genres", []) if str(value).strip()]
        channels.append(
            {
                "key": f"{number}:{identifier or name}",
                "name": name,
                "channelNumber": number,
                "contentId": identifier,
                "logo": f"/channel-logos/all/{filename}",
                "genre": genres[0] if genres else "Other",
                "language": str(channel.get("language") or "Other").strip(),
                "quality": str(channel.get("quality") or "").strip(),
                "vendor": str(channel.get("vendor") or "").strip(),
                "premium": bool(channel.get("isPremium")),
            }
        )
    failed_logos: set[str] = set()
    with ThreadPoolExecutor(max_workers=16) as executor:
        futures = {executor.submit(download_logo, channel, filename): filename for channel, filename in logo_jobs}
        for future in as_completed(futures):
            filename, error = future.result()
            if error:
                failed_logos.add(filename)
    if failed_logos:
        for channel in channels:
            if Path(str(channel["logo"])).name in failed_logos:
                channel["logo"] = None

    channels.sort(key=lambda item: (int(item["channelNumber"]), str(item["name"]).casefold()))

    lines = [
        "// Generated by scripts/update-jio-channel-catalogue.py. Do not edit manually.",
        "import type { JioCatalogueChannel } from './types';",
        "",
        f"export const jioCatalogueUpdatedAt = {json.dumps(updated_at)};",
        "export const jioChannels: JioCatalogueChannel[] = [",
    ]
    for channel in channels:
        lines.append(f"  {json.dumps(channel, ensure_ascii=False, separators=(',', ':'))},")
    lines.extend([
        "];",
        "",
    ])
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    with_ids = sum(channel["contentId"] is not None for channel in channels)
    print(f"Wrote {len(channels)} Jio channels to {OUTPUT}")
    logo_bytes = sum(path.stat().st_size for path in LOGO_DIRECTORY.iterdir())
    print(f"Guide updated: {updated_at}; searchable content IDs: {with_ids}")
    print(f"Bundled logos: {len(channels) - len(failed_logos)}/{len(channels)} ({logo_bytes / 1024 / 1024:.1f} MiB)")


if __name__ == "__main__":
    main()
